package io.kafka.connect.generated;

import com.fasterxml.jackson.databind.ObjectMapper;
import java.net.URI;
import java.net.URLEncoder;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.Map;
import org.apache.kafka.connect.data.Schema;
import org.apache.kafka.connect.errors.ConnectException;
import org.apache.kafka.connect.source.SourceRecord;
import org.apache.kafka.connect.source.SourceTask;

/**
 * Hand-written connector for Yahoo Finance Price.
 *
 * The Airbyte manifest for this source uses Jinja2 control flow ({% if %}) to iterate
 * through a comma-separated tickers list using the PageIncrement page number as an array
 * index. That pattern cannot be auto-generated by the codegen, so this task is written
 * directly in Java.
 *
 * Each poll() call fetches price data for ONE ticker (identified by the stored tickerIndex
 * offset). The framework calls poll() in a loop, so all tickers are covered in sequence.
 * After the last ticker the index resets to 0 and the cycle repeats.
 *
 * Yahoo Finance returns HTTP 403 for some tickers (e.g. crypto pairs). Per the manifest's
 * error_handler, a 403 is treated as a successful empty response rather than an error.
 */
public final class YahooFinancePriceSourceTask extends SourceTask {
  private static final ObjectMapper MAPPER = new ObjectMapper();
  private static final String BASE_URL = "https://query1.finance.yahoo.com";
  private static final String STREAM_NAME = "price";

  private YahooFinancePriceConnectorConfig config;
  private HttpClient httpClient;

  @Override
  public String version() {
    return "1.0.0";
  }

  @Override
  public void start(Map<String, String> props) {
    this.config = new YahooFinancePriceConnectorConfig(props);
    this.httpClient = HttpClient.newHttpClient();
  }

  @Override
  public List<SourceRecord> poll() throws InterruptedException {
    return pollPrice();
  }

  private List<SourceRecord> pollPrice() throws InterruptedException {
    // Read the stored ticker index so restarts resume from the right ticker.
    Map<String, Object> stored = context.offsetStorageReader()
        .offset(Map.of("stream", STREAM_NAME));
    int tickerIndex = 0;
    if (stored != null && stored.get("ticker_index") instanceof Number n) {
      tickerIndex = n.intValue();
    }

    String[] tickers = config.getTickers().split(",");
    if (tickers.length == 0) {
      return Collections.emptyList();
    }
    // Guard against a stored index that is now out of range (user changed tickers config).
    if (tickerIndex >= tickers.length) {
      tickerIndex = 0;
    }

    String ticker = tickers[tickerIndex].strip();
    int nextIndex = (tickerIndex + 1 >= tickers.length) ? 0 : tickerIndex + 1;

    String url = BASE_URL + "/v8/finance/chart/"
        + URLEncoder.encode(ticker, StandardCharsets.UTF_8)
        + "?range=" + URLEncoder.encode(config.getRange(), StandardCharsets.UTF_8)
        + "&interval=" + URLEncoder.encode(config.getInterval(), StandardCharsets.UTF_8)
        + "&symbol=" + URLEncoder.encode(ticker, StandardCharsets.UTF_8);

    try {
      HttpRequest request = HttpRequest.newBuilder()
          .uri(URI.create(url))
          .header("Accept", "application/json")
          .header("User-Agent", "Mozilla/5.0 (X11; Linux x86_64)")
          .GET()
          .build();

      HttpResponse<String> response = sendWithRetry(request);

      // Per manifest error_handler: treat 403 as success (empty result) — Yahoo Finance
      // returns 403 for some tickers (delisted, restricted, crypto pairs, etc.)
      if (response.statusCode() == 403) {
        return Collections.singletonList(emptyRecord(nextIndex));
      }

      if (response.statusCode() < 200 || response.statusCode() >= 300) {
        throw new ConnectException("HTTP " + response.statusCode() + " fetching ticker " + ticker);
      }

      Object json = MAPPER.readValue(response.body(), Object.class);
      String value = MAPPER.writeValueAsString(json);

      SourceRecord record = new SourceRecord(
          Map.of("stream", STREAM_NAME),
          Map.of("ticker_index", nextIndex),
          STREAM_NAME,
          Schema.STRING_SCHEMA,
          value
      );
      return Collections.singletonList(record);

    } catch (InterruptedException e) {
      Thread.currentThread().interrupt();
      throw new ConnectException("Interrupted while polling ticker " + ticker, e);
    } catch (ConnectException e) {
      throw e;
    } catch (Exception e) {
      throw new ConnectException("Failed to poll ticker " + ticker, e);
    }
  }

  // Returns a tombstone-style record carrying only the next offset so the framework
  // commits the advanced ticker_index even when a 403 returns no payload.
  private SourceRecord emptyRecord(int nextIndex) {
    return new SourceRecord(
        Map.of("stream", STREAM_NAME),
        Map.of("ticker_index", nextIndex),
        STREAM_NAME,
        Schema.STRING_SCHEMA,
        "{}"
    );
  }

  private HttpResponse<String> sendWithRetry(HttpRequest request) throws Exception {
    int attempt = 0;
    while (true) {
      HttpResponse<String> resp = httpClient.send(request, HttpResponse.BodyHandlers.ofString());
      if ((resp.statusCode() == 429 || resp.statusCode() >= 500) && attempt < 3) {
        Thread.sleep(1000L << attempt);
        attempt++;
        continue;
      }
      return resp;
    }
  }

  @Override
  public void stop() {
    if (httpClient instanceof AutoCloseable ac) {
      try {
        ac.close();
      } catch (Exception ignored) {
      }
    }
    httpClient = null;
  }
}
